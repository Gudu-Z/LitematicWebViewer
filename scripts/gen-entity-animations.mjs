// 从项目使用的 1.21.11 参考源码转录待机关键帧，不解析/执行 Java。
// 输入：scripts/_ref/*Animations.java；输出：src/entityAnimationData.js。
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
const root = new URL('../', import.meta.url)
const selections = {
  Breeze: ['IDLING'], Bat: ['FLYING', 'ROOSTING'], Camel: ['IDLING', 'SITTING'],
  Frog: ['IDLING_IN_WATER'], CopperGolem: ['SPIN_HEAD'], Armadillo: ['SCARED'],
}
const number = text => {
  const value = text.trim().replace(/[fF]$/, '')
  if (!/^-?\d+(?:\.\d+)?$/.test(value)) throw new Error('Unsupported Java number: ' + text)
  return Number(value)
}
function calls(source, name) {
  const result = []
  let cursor = 0
  while ((cursor = source.indexOf(name + '(', cursor)) !== -1) {
    const start = cursor + name.length + 1
    let end = start, depth = 1
    for (; end < source.length && depth; end++) {
      if (source[end] === '(') depth++
      if (source[end] === ')') depth--
    }
    if (depth) throw new Error('Unbalanced ' + name)
    result.push(source.slice(start, end - 1))
    cursor = end
  }
  return result
}
export function parseAnimation(source, name) {
  source = source.replace(/\s+/g, ' ')
  const match = source.match(new RegExp(`AnimationDefinition ${name} = ([\\s\\S]*?)\\.build\\(\\);`))
  if (!match) throw new Error(`${name} not found`)
  const body = match[1]
  const length = number(body.match(/Builder.create\(([^)]+)\)/)[1])
  const tracks = calls(body, '.addBoneAnimation').map(track => {
    const part = track.match(/^\s*"([^"]+)"/)[1]
    const target = track.match(/Targets\.(\w+)/)[1]
    const frames = calls(track, 'new Keyframe').map(frame => {
      const time = number(frame.slice(0, frame.indexOf(',')))
      const vector = frame.match(/AnimationHelper\.create(\w+)Vector\(([^)]+)\)/)
      if (!vector) throw new Error('Unsupported keyframe: ' + frame)
      let values = vector[2].split(',').map(number)
      if (target === 'ROTATE') values = values.map(n => n * Math.PI / 180)
      if (target === 'MOVE_ORIGIN') values[1] *= -1
      const interpolation = frame.match(/Interpolations\.(\w+)/)[1]
      if (!['LINEAR', 'CUBIC'].includes(interpolation)) throw new Error(interpolation)
      return [time, ...values, interpolation === 'CUBIC' ? 1 : 0]
    })
    if (!frames.length) throw new Error('Empty animation: ' + name)
    return { part, target, frames }
  })
  return { length, loop: body.includes('.looping()'), tracks }
}
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const data = {}
  for (const [entity, names] of Object.entries(selections)) {
    const source = readFileSync(new URL(`scripts/_ref/${entity}Animations.java`, root), 'utf8')
    for (const name of names) {
      data[entity + '.' + name] = parseAnimation(source, name)
    }
  }
  const output = new URL('src/entityAnimationData.js', root)
  writeFileSync(output, '// Generated by scripts/gen-entity-animations.mjs from vanilla animation definitions.\nexport const ENTITY_ANIMATIONS = ' + JSON.stringify(data) + '\n')
  console.log(`Generated ${Object.keys(data).length} vanilla animations → ${fileURLToPath(output)}`)
}
