// Minecraft 26.3 独立幼年模型的待机关键帧，--fetch 下载可核对的源码缓存。
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { parseAnimation } from './gen-entity-animations.mjs'
const root = new URL('./_ref/baby26/', import.meta.url)
const selections = {
  BabyAxolotlAnimation: ['BABY_AXOLOTL_IDLE_FLOOR', 'IDLE_UNDERWATER'],
  CamelBabyAnimation: ['CAMEL_BABY_SIT_POSE', 'CAMEL_BABY_IDLE'],
  BabyArmadilloAnimation: ['ARMADILLO_BABY_PEEK'],
}
const data = {}, sources = {}
await mkdir(root, { recursive: true })
for (const [file, names] of Object.entries(selections)) {
  const url = `https://mc-packet-reference.netlify.app/26.x/source/net/minecraft/client/animation/definitions/${file.toLowerCase()}/`
  const cache = new URL(file + '.java', root)
  if (process.argv.includes('--fetch')) {
    const response = await fetch(url)
    if (!response.ok) throw Error(url)
    const html = await response.text()
    const source = [...html.matchAll(/<td class="cv-code"><pre><code>([\s\S]*?)<\/code>/g)].map(m => m[1]
      .replaceAll('&lt;', '<').replaceAll('&gt;', '>').replaceAll('&quot;', '"').replaceAll('&#39;', "'").replaceAll('&amp;', '&')).join('\n')
    if (!source.includes('class ' + file)) throw Error('缺失源码：' + file)
    await writeFile(cache, source)
  }
  const source = await readFile(cache, 'utf8')
  sources[file] = { url, sha256: createHash('sha256').update(source).digest('hex') }
  const converted = source.replaceAll('Builder.withLength', 'Builder.create').replaceAll('.addAnimation(', '.addBoneAnimation(')
    .replaceAll('Targets.ROTATION', 'Targets.ROTATE').replaceAll('Targets.POSITION', 'Targets.MOVE_ORIGIN')
    .replaceAll('KeyframeAnimations.degreeVec', 'AnimationHelper.createRotationalVector')
    .replaceAll('KeyframeAnimations.posVec', 'AnimationHelper.createTranslationalVector')
    .replaceAll('KeyframeAnimations.scaleVec', 'AnimationHelper.createScalingVector').replaceAll('Interpolations.CATMULLROM', 'Interpolations.CUBIC')
  for (const name of names) data[name] = parseAnimation(converted, name)
}
await writeFile(new URL('../src/babyAnimationData.js', import.meta.url), '// Generated by scripts/gen-baby-animations.mjs from Minecraft 26.3 animation definitions.\n'
  + `export const BABY_ANIMATION_SOURCES = ${JSON.stringify(sources)}\nexport const BABY_ANIMATIONS = ${JSON.stringify(data)}\n`)
console.log(`Generated ${Object.keys(data).length} baby animations`)
